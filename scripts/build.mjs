import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envUrl = process.env.SUPABASE_URL || "";
const envKey = process.env.SUPABASE_ANON_KEY || "";

function writeConfig() {
  const file = path.join(root, "config.js");
  if (envUrl && envKey) {
    const body = `/* generated by scripts/build.mjs at ${new Date().toISOString()} */
window.XMX_CONFIG = {
  supabaseUrl: ${JSON.stringify(envUrl)},
  supabaseAnonKey: ${JSON.stringify(envKey)},
  storageBucket: ${JSON.stringify(process.env.SUPABASE_STORAGE_BUCKET || "product-images")},
  appVersion: "5.0.0",
  demoFallback: false
};
`;
    fs.writeFileSync(file, body, "utf8");
    console.log("config.js 已从环境变量生成");
    return;
  }
  if (!fs.existsSync(file)) {
    fs.copyFileSync(path.join(root, "config.example.js"), file);
    console.log("config.js 不存在，已复制示例配置（需要填写后才能连接云端）");
  } else {
    console.log("config.js 已存在，保留原内容（未设置 SUPABASE_URL / SUPABASE_ANON_KEY）");
  }
}

writeConfig();

const result = await build({
  entryPoints: [path.join(root, "src/main.js")],
  outfile: path.join(root, "app.js"),
  bundle: true,
  format: "iife",
  target: ["es2020"],
  platform: "browser",
  minify: process.env.DEV !== "1",
  sourcemap: "external",
  legalComments: "none",
  logLevel: "info",
  define: {
    "process.env.NODE_ENV": JSON.stringify(process.env.NODE_ENV || "production")
  }
});

if (result.errors.length) {
  console.error(result.errors);
  process.exit(1);
}

const app = fs.statSync(path.join(root, "app.js"));
console.log(`app.js 构建完成：${(app.size / 1024).toFixed(1)} KB`);
