import { chromium } from "playwright-core";
import fs from "node:fs";
import path from "node:path";
import JSZip from "jszip";

const edge = "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe";
const browser = await chromium.launch({ executablePath: edge, headless: true, args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1280, height: 1100 }, acceptDownloads: true });
const page = await context.newPage();
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto("http://127.0.0.1:8765/?demo=1#/w/gyly/c/xmx/catalog", { waitUntil: "networkidle", timeout: 120000 });
await page.waitForFunction(() => document.querySelector("#totalCount")?.textContent === "1537", null, { timeout: 60000 });
await page.waitForTimeout(1000);
await page.locator("#accountBtn").click();
await page.locator("#accountDialog[open]").waitFor();
await page.locator("[data-account-action='backup']").click();
await page.locator("#backupDialog[open]").waitFor();
console.log("starting full backup", new Date().toISOString());
const started = Date.now();
const downloadPromise = page.waitForEvent("download", { timeout: 600000 });
await page.locator("#backupStart").click();
const download = await downloadPromise;
const out = path.resolve("test-artifacts", "backup-full.zip");
await download.saveAs(out);
console.log("downloaded", new Date().toISOString(), "ms", Date.now() - started, "size", fs.statSync(out).size);
const zip = await JSZip.loadAsync(fs.readFileSync(out));
const manifest = JSON.parse(await zip.file("manifest.json").async("string"));
const data = JSON.parse(await zip.file("data.json").async("string"));
console.log("zip entries", Object.keys(zip.files).length);
console.log("manifest images", manifest.images.length, "base", manifest.images.filter((x) => x.category === "base").length, "uploads", manifest.images.filter((x) => x.category === "upload").length);
console.log("products", data.counts.products, "warnings", manifest.warnings.length);
console.log("has composite", manifest.images.some((x) => x.sourcePath.includes("/images/img_")));
console.log("has thumb", manifest.images.some((x) => x.sourcePath.includes("/thumbs/")));
await browser.close();
